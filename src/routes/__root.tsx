function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      {/* The whole app is client-only: auth lives in localStorage and the voice
          pipeline needs the browser. */}
      <ClientOnly fallback={<div className="min-h-dvh bg-cream" />}>
        <AppShell>
          <Outlet />
        </AppShell>
      </ClientOnly>
    </QueryClientProvider>
  );
}
